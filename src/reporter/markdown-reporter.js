'use strict';
const fs = require('fs');
const path = require('path');
const { formatBytes } = require('../utils/format');
const { buildReport } = require('./json-reporter');

function generateMarkdown(scanResult) {
  const report = buildReport(scanResult);
  const s = report.summary;
  const top10 = [...(report.packages||[])].sort((a,b)=>b.size-a.size).slice(0,10);

  let md = `# 📦 NodeSlim 分析报告\n\n`;
  md += `> **项目**: \`${report.meta.root}\`  \n`;
  md += `> **包管理器**: ${report.meta.packageManager}  \n`;
  md += `> **生成时间**: ${new Date(report.meta.generatedAt).toLocaleString('zh-CN')}  \n`;
  md += `> **版本**: v${report.meta.version}\n\n`;

  md += `## 📊 统计摘要\n\n`;
  md += `| 指标 | 数值 |\n|------|------|\n`;
  md += `| 总包数 | ${s.totalPackages} |\n`;
  md += `| 总体积 | ${formatBytes(s.totalSize)} |\n`;
  md += `| 总文件数 | ${s.totalFiles} |\n`;
  md += `| 重复依赖 | ${s.duplicateCount} 个 (浪费 ${formatBytes(s.wastedSize)}) |\n`;
  md += `| 可优化 | ${formatBytes(s.optimizableSize)} |\n\n`;

  md += `## 🔝 Top 10 最大包\n\n`;
  md += `| # | 包名 | 体积 | 文件数 | 类型 | 安装次数 |\n|---|------|------|--------|------|----------|\n`;
  top10.forEach((p,i) => {
    md += `| ${i+1} | \`${p.name}@${p.version}\` | ${formatBytes(p.size)} | ${p.fileCount} | ${p.category} | ${p.installCount} |\n`;
  });
  md += `\n`;

  if (report.duplicates?.length) {
    md += `## ♻️ 重复依赖\n\n`;
    md += `| 包名 | 次数 | 版本 | 总计 | 浪费 |\n|------|------|------|------|------|\n`;
    report.duplicates.slice(0,15).forEach(d => {
      md += `| \`${d.packageName}\` | ${d.count} | ${d.versions.join(', ')} | ${formatBytes(d.totalSize)} | ${formatBytes(d.wastedSize)} |\n`;
    });
    md += `\n`;
  } else {
    md += `## ♻️ 重复依赖\n\n✅ 无重复依赖\n\n`;
  }

  if (report.bloat?.length) {
    md += `## 🐘 膨胀包\n\n`;
    md += `| 包名 | 体积 | 文件数 | 原因 |\n|------|------|--------|------|\n`;
    report.bloat.slice(0,10).forEach(b => {
      md += `| \`${b.name}@${b.version}\` | ${b.sizeFormatted} | ${b.fileCount} | ${b.reason} |\n`;
    });
    md += `\n`;
  }

  if (report.suggestions?.length) {
    md += `## 💡 优化建议\n\n`;
    report.suggestions.forEach((sug, idx) => {
      md += `### ${idx+1}. [${sug.type}] ${sug.message}\n\n`;
      md += `- **建议**: ${sug.suggestion}\n`;
      if (sug.estimatedSavings) md += `- **预计节省**: ${sug.estimatedSavings}\n`;
      md += `\n`;
    });
  }

  if (report.security?.length) {
    md += `## 🔒 安全问题\n\n`;
    md += `| 级别 | 包名 | 问题 | 建议 |\n|------|------|------|------|\n`;
    report.security.forEach(sec => {
      md += `| ${sec.severity} | \`${sec.packageName}\` | ${sec.message} | ${sec.suggestion} |\n`;
    });
    md += `\n`;
  } else {
    md += `## 🔒 安全扫描\n\n✅ 未发现已知漏洞\n\n`;
  }

  md += `---\n*Generated by NodeSlim v${report.meta.version}*\n`;
  return md;
}

async function saveMarkdownReport(scanResult, opts = {}) {
  const outputDir = opts.outputDir || path.join(scanResult.root, '.nodeslim/reports');
  fs.mkdirSync(outputDir, { recursive: true });
  const md = generateMarkdown(scanResult);
  const filename = opts.filename || `report-${new Date().toISOString().slice(0,10)}-${Date.now()}.md`;
  const full = path.join(outputDir, filename);
  fs.writeFileSync(full, md, 'utf-8');
  fs.writeFileSync(path.join(outputDir, 'latest.md'), md, 'utf-8');
  return { path: full, markdown: md };
}

module.exports = { generateMarkdown, saveMarkdownReport };
